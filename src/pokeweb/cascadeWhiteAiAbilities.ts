export function cascadeWhiteAiAbilitiesForSpecies(speciesId: number): CascadeWhiteAiAbilitySlot | undefined {
  if (!Number.isInteger(speciesId) || speciesId < 0) return undefined;
  const normalizedSpeciesId = speciesId > 1024 ? speciesId % 1024 : speciesId;
  for (const range of AI_ABILITY_RANGES) {
    if (normalizedSpeciesId >= range.start && normalizedSpeciesId <= range.end) return range.abilities;
  }
  return undefined;
}

