import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { serializeCalcAbilityCatalog } from "../src/pokeweb/calcAbilityCatalog";

const args = process.argv.slice(2);
const check = args.includes("--check");
const output = args.find(arg => arg !== "--check");
if (!output) throw Error("Pass the calculator catalog file path.");
const entries = serializeCalcAbilityCatalog();
const fingerprint = createHash("sha256").update(entries).digest("hex");
const catalog = `{"protocol":1,"fingerprint":"${fingerprint}","entries":${entries}}`;
const files = [
  [resolve("src/assets/data/calcAbilityManifest.json"), JSON.stringify({ protocol: 1, fingerprint }) + "\n"],
  [resolve(output), `// Generated by Pokeweb's sync-calc-ability-catalog.ts.\n(function (catalog) {\n    if (typeof module === "object" && module.exports) module.exports = catalog;\n    else globalThis.PokewebAbilityCatalog = catalog;\n})(${catalog});\n`],
] as const;
for (const [path, data] of files) {
  if (!check) await writeFile(path, data);
  else if (await readFile(path, "utf8") !== data) throw Error(`Stale ability catalog output: ${path}`);
}
