// In-memory verification: source ROMs and user saves are never written.
import { readFile } from "node:fs/promises";
import { basename } from "node:path";
import assert from "node:assert/strict";
import { NARC } from "../src/nds/narc";
import { NintendoDSRom } from "../src/nds/rom";
import { loadProjectFromRomBytes } from "../src/pokeweb/loader";
import { exportModifiedRom } from "../src/pokeweb/exportRom";
import { parseGen5MatrixFile, materializeGen5MatrixFile } from "../src/pokeweb/gen5MatrixModel";
import { addMatrixHeaderTable, applyMatrixCellEdit, createMatrix, duplicateMatrix, getMatrixSnapshot, linkHeaderToMatrix, loadMatrixEditorData, resizeMatrix, GEN5_MATRIX_EMPTY } from "../src/pokeweb/matrixModel";
import { createProjectDocument } from "../src/pokeweb/projectDocument";
import { openProjectSession } from "../src/pokeweb/projectSession";
import { createNarcStore } from "../src/pokeweb/projectStore";
import { parseHeaders } from "../src/pokeweb/headerModel";
import { loadMap3dZone } from "../src/pokeweb/map3dModel";

const path = process.argv[2];
if (!path) throw new Error("Usage: npx vite-node scripts/verify-matrix-editor.ts /path/to/gen5.nds");
const source = new Uint8Array(await readFile(path));
const project = await loadProjectFromRomBytes(source, basename(path), { selectedNarcs: ["headers"] });
await loadMatrixEditorData(project);
const store = project.narcs.matrix!;
assert(store, "matrix archive loaded");
const originals = store.rawFiles.map(bytes => bytes.slice());
for (const bytes of originals) assert.deepEqual(materializeGen5MatrixFile(parseGen5MatrixFile(bytes), bytes), bytes, "original matrix round trip");
const world = getMatrixSnapshot(project, 0);
const fillerCell = world.cells.find(cell => cell.headerId === GEN5_MATRIX_EMPTY && cell.mapId !== GEN5_MATRIX_EMPTY);
assert(fillerCell, "world matrix has a populated cell with no assigned header");
const matrixCell = { matrixId: 0, x: fillerCell.x, y: fillerCell.y };
const filler = await loadMap3dZone(project, 0, { matrixCell });
assert.equal(filler.chunks.length, 1, "unassigned cell loads exactly its own map chunk");
assert.equal(filler.chunks[0].sourceChunkId, fillerCell.mapId, "preview uses selected map ID");
assert.equal(filler.chunks[0].matrixX, fillerCell.x, "preview retains matrix X");
assert.equal(filler.chunks[0].matrixY, fillerCell.y, "preview retains matrix Y");
assert(filler.chunks[0].primitives.some(p => p.indices.length), "selected map has actual rendered geometry");
assert.equal(filler.entities.length, 0, "unassigned cell does not borrow another header's events");
assert.equal(filler.npcModels.length, 0, "unassigned cell does not borrow another header's NPCs");
const anotherCell = world.cells.find(cell => cell.index !== fillerCell.index && cell.headerId === GEN5_MATRIX_EMPTY && cell.mapId !== GEN5_MATRIX_EMPTY)!;
const anotherFiller = await loadMap3dZone(project, 0, { matrixCell: { matrixId: 0, x: anotherCell.x, y: anotherCell.y } });
assert.notEqual(anotherFiller, filler, "direct cell coordinates participate in the scene cache key");
assert.equal(anotherFiller.chunks[0].sourceChunkId, anotherCell.mapId);
const header = Object.values(project.headers!.rows).find(row => Number(row.matrix_id) === 1);
assert(header, "small matrix has a referencing header");
const scene = await loadMap3dZone(project, header.index);
assert.equal(await loadMap3dZone(project, header.index), scene, "unchanged scene is cached");
const mapId = getMatrixSnapshot(project, 1).cells[0].mapId;
applyMatrixCellEdit(project, 1, [0], { mapId: GEN5_MATRIX_EMPTY });
const emptyScene = await loadMap3dZone(project, header.index);
assert.notEqual(emptyScene, scene, "matrix revision invalidates scene cache");
assert.equal(emptyScene.chunks.length, 0, "viewer consumes current matrix cells");
applyMatrixCellEdit(project, 1, [0], { mapId });
const duplicate = duplicateMatrix(project, 1), created = createMatrix(project);
resizeMatrix(project, duplicate, 2, 2);
addMatrixHeaderTable(project, duplicate, header.index);
applyMatrixCellEdit(project, duplicate, [1], { mapId, headerId: header.index });
linkHeaderToMatrix(project, duplicate, header.index);
const linkedScene = await loadMap3dZone(project, header.index);
assert.equal(linkedScene.matrixId, duplicate, "explicit link invalidates cached header routing");
assert.equal(linkedScene.chunks.length, 2, "viewer loads resized appended matrix");
const restored = openProjectSession(structuredClone(createProjectDocument(project, false)));
assert.equal(getMatrixSnapshot(restored, duplicate).width, 2, "save/reopen preserves dimensions");
assert.equal(restored.headers!.rows[header.index + 1].matrix_id, duplicate, "save/reopen preserves header link");
const exported = new NintendoDSRom(await exportModifiedRom(project), { fileData: "view" });
const reopenedMatrices = new NARC(exported.files[store.fileId]);
assert.equal(reopenedMatrices.files.length, originals.length + 2, "ROM export keeps appended matrices");
for (let i = 0; i < originals.length; i++) assert.deepEqual(reopenedMatrices.files[i], originals[i], `existing matrix ${i} preserved`);
assert.deepEqual(reopenedMatrices.files[duplicate], project.narcs.matrix!.rawFiles[duplicate], "ROM export keeps matrix edits");
assert.equal(parseGen5MatrixFile(reopenedMatrices.files[created]).map_0, GEN5_MATRIX_EMPTY, "blank new matrix exported");
const headerStore = project.narcs.headers!;
restored.narcs.headers = createNarcStore("headers", headerStore.sourcePath, headerStore.fileId, new NARC(exported.files[headerStore.fileId]));
restored.headers = parseHeaders(restored);
assert.equal(restored.headers.rows[header.index + 1].matrix_id, duplicate, "ROM export keeps header link");
console.log(JSON.stringify({ rom: basename(path), version: project.session.baseVersion, originalMatrices: originals.length,
  byteIdenticalRoundTrips: originals.length, existingMatricesPreserved: originals.length, appendedMatrices: 2,
  lazyArchives: true, saveReopen: true, romExport: true, viewerCellsAndCache: true,
  unassignedCell: { mapId: fillerCell.mapId, x: fillerCell.x, y: fillerCell.y, chunks: filler.chunks.length, resourceHeader: filler.zoneId, events: filler.entities.length } }));
