import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { NintendoDSRom } from "../../src/nds/rom";
import { NARC } from "../../src/nds/narc";
import { loadProjectFromRomBytes } from "../../src/pokeweb/loader";
import { exportModifiedRom } from "../../src/pokeweb/exportRom";
import { getCGearQuickActionsStatus, installCGearQuickActions, disableCGearQuickActions } from "../../src/pokeweb/cgearQuickActionsModel";
import { getPokenavStatus, installPokenav } from "../../src/pokeweb/pokenavModel";
import { listCodeInjectionDlls } from "../../src/pokeweb/pmcModel";
import { ensureCGearButtons } from "../../src/pokeweb/cgearButtonsModel";
import { newButton } from "../../src/cgearButtons/document";
import { parseRpm } from "../../src/pokeweb/rpm";
import redux from "../../src/assets/codeinjection/cgearQuickActionsReduxManifest.json";

const [input, output] = process.argv.slice(2);
if (!input) throw new Error("Usage: vite-node runtime/cgear-quick-actions/verify_redux_install.ts INPUT.nds [NEW_OUTPUT.nds]");
globalThis.fetch = async input => {
  const url = input instanceof URL ? input : new URL(String(input));
  if (url.protocol !== "file:") throw new Error("This verifier only loads local bundled assets.");
  return new Response(new Uint8Array(await readFile(url)));
};
const bytes = new Uint8Array(await readFile(input)), original = new NintendoDSRom(bytes, { fileData: "view" });
const project = await loadProjectFromRomBytes(bytes, "redux.nds", { selectedNarcs: ["message_texts"] });
const originals = listCodeInjectionDlls(project).map(module => ({ path: module.path, bytes: original.getFileByName(module.path).slice() }));
assert.equal(getCGearQuickActionsStatus(project).romProfile, "redux");
assert.equal(getPokenavStatus(project).compatible, true);
await installCGearQuickActions(project);
assert.equal(getCGearQuickActionsStatus(project).updateAvailable, false);
await installPokenav(project);
const design = ensureCGearButtons(project).document;
if (!design.buttons.some(button => button.action === "pokenav")) design.buttons.push(newButton(design, "pokenav"));
await installCGearQuickActions(project);
const exported = await exportModifiedRom(project), rom = new NintendoDSRom(exported, { fileData: "view" });
for (const module of originals) assert.deepEqual(rom.getFileByName(module.path), module.bytes);
assert.deepEqual(rom.loadArm9Overlays([36]).get(36)!.data, original.loadArm9Overlays([36]).get(36)!.data);
const scripts = new NARC(rom.getFileByName(redux.pcScript.archive)), originalScripts = new NARC(original.getFileByName(redux.pcScript.archive));
assert.equal(scripts.files.length, originalScripts.files.length);
for (let i = 0; i < scripts.files.length; ++i) assert.deepEqual(scripts.files[i], originalScripts.files[i]);
const status = getCGearQuickActionsStatus(project), rpm = parseRpm(rom.getFileByName(status.dllPath!), { allowedMagics: ["DLXF"] });
assert.equal(rpm.metadata.PMCVersion, redux.version);
assert(!rpm.relocations.some(r => r.target.module === "36" && [0x21824bc, 0x21a0b2c].includes(r.target.address)));
const reimported = await loadProjectFromRomBytes(exported, "reimport.nds", { selectedNarcs: ["message_texts"] });
assert.equal(getCGearQuickActionsStatus(reimported).romProfile, "redux");
assert.equal(getCGearQuickActionsStatus(reimported).compatible, true);
assert.equal(getCGearQuickActionsStatus(reimported).updateAvailable, false);
assert.equal(getPokenavStatus(reimported).installed, true);
assert.equal(getPokenavStatus(reimported).enabled, true);
assert.equal(ensureCGearButtons(reimported).document.buttons.length, 7);
const count = listCodeInjectionDlls(reimported).length;
await installCGearQuickActions(reimported); await installPokenav(reimported);
assert.equal(listCodeInjectionDlls(reimported).length, count);
disableCGearQuickActions(project); assert.equal(getCGearQuickActionsStatus(project).enabled, false);
await installCGearQuickActions(project); assert.equal(getCGearQuickActionsStatus(project).enabled, true);
if (output) await writeFile(output, exported, { flag: "wx" });
console.log("Redux adapter, PC and NAV buttons, export/reimport/reinstall, disable/re-enable, and original DLL/script/encounter-code preservation verified.");
