"""Generate the bounded stock-move classification table from shipped data."""
import json
from pathlib import Path
HERE=Path(__file__).resolve().parent
source=json.loads((HERE.parents[1]/'src/assets/data/abilityMoveClasses.json').read_text())
assert source['version']==1 and source['maximumMoveId']==559
rows={}
for bit,name in enumerate(['bite','pulse','ball','slicing','powder','wind','healing']):
    values=source['classes'][name]
    assert values==sorted(set(values)) and all(1<=v<=559 for v in values)
    for move in values:rows[move]=rows.get(move,0)|(1<<bit)
(HERE/'move_classes.h').write_text('/* Generated by generate_move_classes.py; classification facts, not ROM flags. */\nstatic const u16 abilityMoveClasses[][2]={\n'+''.join(f' {{{move},{bits}}},\n' for move,bits in sorted(rows.items()))+'};\n')
print(f'{len(rows)} stock moves classified.')
